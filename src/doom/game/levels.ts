import type { LevelDef } from "./map";

/**
 * The level set, authored as ASCII art. See `map.ts` for the legend.
 *
 * Rows are run through `enclose` rather than trusted verbatim: it pads every
 * row to the widest one and forces the outer ring to solid wall. A miscounted
 * row then produces a slightly odd-shaped room instead of a hole the player can
 * walk through into unallocated memory, which is the only failure mode here
 * that isn't self-evident on screen.
 *
 * Each level is one connected space with wall stubs and pillar clusters for
 * cover, plus a keyed room and a locked door on the way to the exit. Keeping
 * the topology open rather than maze-like is deliberate: it is trivially
 * verifiable that nothing is sealed off, and it plays better than a labyrinth.
 */
function enclose(rows: string[]): string[] {
	const width = Math.max(...rows.map((r) => r.length));
	return rows.map((row, y) => {
		const padded = row.padEnd(width, "#");
		if (y === 0 || y === rows.length - 1) return "#".repeat(width);
		return `#${padded.slice(1, width - 1)}#`;
	});
}

