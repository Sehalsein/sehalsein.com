export const GLYPH_W = 5;
export const GLYPH_H = 7;

/** Pixel width of `text` at `scale`, including inter-glyph spacing. */
export function textWidth(text: string, scale = 1): number {
	if (text.length === 0) return 0;
	return text.length * (GLYPH_W + 1) * scale - scale;
}

export interface TextOptions {
	scale?: number;
	/** Solid drop shadow offset by one scaled pixel — keeps text readable. */
	shadow?: Color;
}

/** Draw `text` with its top-left corner at (x, y). Returns the width drawn. */
export function drawText(
	fb: Framebuffer,
	text: string,
	x: number,
	y: number,
	color: Color,
	options: TextOptions = {},
): number {
	const scale = Math.max(1, Math.round(options.scale ?? 1));
	const upper = text.toUpperCase();
	let cursor = Math.round(x);
	for (const char of upper) {
		const glyph = GLYPHS[char] ?? GLYPHS["?"];
		for (let row = 0; row < GLYPH_H; row++) {
			const bits = glyph[row];
			for (let col = 0; col < GLYPH_W; col++) {
				if (bits[col] !== "1") continue;
				const px = cursor + col * scale;
				const py = Math.round(y) + row * scale;
				if (options.shadow !== undefined) {
					fb.fillRect(px + scale, py + scale, scale, scale, options.shadow);
				}
				fb.fillRect(px, py, scale, scale, color);
			}
		}
		cursor += (GLYPH_W + 1) * scale;
	}
	return cursor - Math.round(x) - scale;
}

/** Draw `text` centered horizontally on `centerX`. */
export function drawTextCentered(
	fb: Framebuffer,
	text: string,
	centerX: number,
	y: number,
	color: Color,
	options: TextOptions = {},
): void {
	const scale = Math.max(1, Math.round(options.scale ?? 1));
	drawText(fb, text, centerX - textWidth(text, scale) / 2, y, color, options);
}

/** Draw `text` so it ends at `rightX` — for right-aligned HUD counters. */
export function drawTextRight(
	fb: Framebuffer,
	text: string,
	rightX: number,
	y: number,
	color: Color,
	options: TextOptions = {},
): void {
	const scale = Math.max(1, Math.round(options.scale ?? 1));
	drawText(fb, text, rightX - textWidth(text, scale), y, color, options);
}
